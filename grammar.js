/// <reference types="tree-sitter-cli/dsl" />
// Bend 2 surface syntax. See guide/GUIDE.md and bend2/bend.ts in bendlang/bend.
const oneOf = rules => rules.length === 1 ? rules[0] : choice(...rules);
const commaSep = rule => optional(seq(rule, repeat(seq(optional(','), rule)), optional(',')));

module.exports = grammar({
  name: 'bend2',
  word: $ => $.identifier,
  reserved: { global: $ => [
    'def', 'type', 'law', 'match', 'case', 'do', 'return', 'for', 'exs',
    'where', 'is', 'import', 'Type', 'Data', 'Kind', 'Quant',
  ] },
  extras: $ => [/\s/, $.comment],
  // Operators with whitespace-sensitive meanings share the layout scanner.
  externals: $ => [
    $._indent, $._dedent, $._same_line, $._add, $._subtract, $._modulo,
    $._less, $._greater, $._greater_equal, $._shift_right, $._error_sentinel,
  ],
  conflicts: $ => [
    [$._expression, $.do_let],
    [$._expression, $.array_update_statement],
    [$.do_body, $.do_step],
    [$._body],
    [$._expression, $.monadic_binding],
    [$.match_arm],
    [$.parallel_let, $._expression],
  ],
  rules: {
    source_file: $ => repeat(choice($.import_declaration, $.type_declaration,
      $.law_declaration, $.function_definition)),
    comment: _ => token(seq('#', /[^\r\n]*/)),
    identifier: _ => /[A-Za-z_](?:[A-Za-z0-9_.]*[A-Za-z0-9_])?/,
    import_declaration: $ => seq('import', choice('Base', seq(
      field('path', $.module_path), 'as', field('alias', $.identifier)))),
    module_path: _ => /(?:\.{1,2}\/|0x[0-9a-fA-F]+\/)[A-Za-z0-9_./-]+/,
    decorator: _ => '@unsafe',
    function_definition: $ => seq(optional($.decorator), 'def',
      field('name', $.identifier), $.parameters,
      optional(seq('->', field('return_type', $._expression))), ':',
      field('body', $._suite)),
    parameters: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(optional(field('quantity', choice('-', '+', '~'))),
      field('name', $.identifier), optional(seq(':', field('type', $._expression)))),
    type_declaration: $ => seq('type', field('name', $.identifier),
      optional($.type_parameters), 'is', field('kind', $._expression), ':',
      optional($.constructors)),
    type_parameters: $ => seq('<', commaSep($.parameter), '>'),
    constructors: $ => choice(
      seq($._indent, repeat1($.constructor_declaration), $._dedent),
      repeat1($.constructor_declaration)),
    constructor_declaration: $ => seq(field('name', $.identifier), '{', commaSep($.parameter), '}'),
    law_declaration: $ => seq('law', field('name', $.identifier), ':',
      choice(seq($._indent, $.law_body, $._dedent), $.law_body)),
    law_body: $ => seq(repeat($.quantifier), $._body),
    quantifier: $ => seq(choice('for', 'exs'),
      optional(field('quantity', choice('+', '-'))), field('name', $.identifier), ':',
      field('type', $._expression), optional(seq('where', field('constraint', $._expression)))),
    _suite: $ => choice($.block, $._body),
    block: $ => seq($._indent, $._body, $._dedent),
    _body: $ => choice($.let_expression, $.parallel_let,
      $.match_expression, $.foreign_body, $.array_update_statement, $._expression),
    foreign_body: $ => prec.right(repeat1($.foreign_import)),
    foreign_import: $ => seq('import', field('path', $.string)),
    let_expression: $ => prec.right(1, seq(optional('-'), field('pattern', $._expression),
      '=', field('value', $._expression), optional(';'), field('body', $._body))),
    parallel_let: $ => prec.right(seq(field('binding', choice($.identifier, $.reusable_expression)),
      repeat1(field('binding', choice($.identifier, $.reusable_expression))), '=',
      field('value', $._expression), repeat1(field('value', $._expression)),
      optional(';'), field('body', $._body))),
    match_expression: $ => prec.right(seq('match', repeat1(seq(
      field('value', $._expression), optional(','))), ':', optional($.match_cases))),
    match_cases: $ => seq($._indent, repeat1($.case_clause), $._dedent),
    case_clause: $ => seq('case', repeat1(seq(field('pattern', $._expression), optional(','))),
      ':', field('body', $._suite)),
    rewrite_expression: $ => prec.right(seq('%', field('proof', $._expression),
      optional(seq('@', field('equality', $._expression))), ':',
      field('motive', $._expression), optional(';'), field('body', $._body))),
    _expression: $ => choice($.identifier, $.kind, $.quantity, $.integer, $.float,
      $.natural, $.successor_expression, $.character, $.string, $.hole,
      $.constructor_expression, $.call_expression, $.type_application,
      $.reusable_expression, $.lambda_expression, $.function_type, $.dependent_type,
      $.binary_expression, $.parenthesized_expression, $.tuple_expression,
      $.annotation_expression, $.equality_type, $.reflexivity,
      $.list_expression, $.array_expression, $.index_expression, $.array_update,
      $.do_expression, $.match_function, $.rewrite_expression),
    kind: $ => choice('Type', 'Data', 'Quant', seq('Kind', '(', $._expression, ')')),
    quantity: _ => /&[012]/,
    integer: _ => /[0-9]+/,
    float: _ => /[0-9]+\.[0-9]+(?:[eE][+-]?[0-9]+)?/,
    natural: _ => /[0-9]+n/,
    successor_expression: $ => prec.right(-1, seq($.natural, token.immediate(prec(2, '+')), $._expression)),
    escape_sequence: _ => token(seq('\\', choice(/[ntr0\\'"]/, /u\{[0-9a-fA-F]+\}/))),
    character: $ => seq("'", choice($.escape_sequence, token.immediate(prec(2, /[^'\\]/))), "'"),
    string: $ => seq('"', repeat(choice($.escape_sequence, $.string_content)), '"'),
    string_content: _ => token.immediate(prec(2, /[^"\\]+/)),
    hole: $ => seq('?', $.identifier),
    constructor_expression: $ => seq(field('name', $.identifier), token.immediate('{'),
      commaSep($._expression), '}'),
    call_expression: $ => prec.left(15, seq(field('function', $._expression),
      optional(field('gpu', '!')), $._same_line, $.arguments)),
    arguments: $ => seq('(', commaSep(choice($._expression, $.template_argument)), ')'),
    template_argument: $ => seq('~', $._expression),
    type_application: $ => prec.dynamic(1, prec.left(15, seq(field('name', $.identifier),
      '<', commaSep($._expression), '>'))),
    reusable_expression: $ => prec(14, seq('+', $._expression)),
    lambda_expression: $ => prec.right(-2, seq(field('parameter', choice($.identifier,
      $.reusable_expression)), '=>', field('body', $._suite))),
    function_type: $ => prec.right(-1, seq(field('domain', $._expression), '->',
      field('codomain', $._expression))),
    dependent_type: $ => prec.right(-1, seq(choice('@', '&'), optional(choice('+', '-')),
      field('name', $.identifier), ':', field('domain', $._expression), '->',
      field('codomain', $._expression))),
    binary_expression: $ => choice(...[
      [1, ['&', '|'], true], [2, ['||']], [3, ['&&']],
      [4, ['<', '<=', '>', '>=']], [5, ['<>', '++', '<&>'], true],
      [6, ['.|.']], [7, ['.^.']], [8, ['.&.']], [9, ['<<', '>>']],
      [10, ['+', '-']], [11, ['*', '/', '%']],
    ].map(([p, ops, right]) => (right ? prec.right : prec.left)(p, seq(
      field('left', $._expression), field('operator', oneOf(ops.map(op => {
        const external = { '+': $._add, '-': $._subtract, '%': $._modulo,
          '<': $._less, '>': $._greater, '>=': $._greater_equal, '>>': $._shift_right };
        return external[op] ? alias(external[op], op) : op;
      }))),
      field('right', $._expression))))),
    parenthesized_expression: $ => seq('(', $._body,
      optional(seq(':', field('type', $._expression))), ')'),
    tuple_expression: $ => seq('(', $._expression, ',', $._expression,
      repeat(seq(',', $._expression)), ')'),
    annotation_expression: $ => seq('{', field('value', $._expression), ':',
      field('type', $._expression), '}'),
    equality_type: $ => seq('{', field('left', $._expression), choice('==', '!='),
      field('right', $._expression), ':', field('type', $._expression), '}'),
    reflexivity: _ => seq('{', '==', '}'),
    list_expression: $ => seq('[', commaSep($._expression), ']'),
    array_expression: $ => seq('[', field('value', $._expression), ':',
      field('type', $._expression), field('allocation', choice('*', '^')),
      field('size', $._expression), ']'),
    index_expression: $ => prec.left(15, seq(field('array', $._expression),
      $._same_line, '[', field('index', $._expression), ']')),
    array_update_statement: $ => prec.right(seq($.array_update, optional(';'), field('body', $._body))),
    array_update: $ => prec.right(1, seq($.index_expression, '<-', field('value', $._expression))),
    do_expression: $ => seq('do', field('monad', $.identifier), '<', commaSep($._expression), '>', ':',
      choice(seq($._indent, $.do_body, $._dedent), $.do_body)),
    do_body: $ => prec.right(seq(repeat(choice($.monadic_binding, $.discard_binding, $.do_let, $.do_step)),
      choice($.return_expression, $._expression))),
    do_let: $ => seq(optional(choice('+', '-')), $.identifier, '=', $._expression, optional(';')),
    discard_binding: $ => seq(field('type', $._expression), '<-', field('value', $._expression), optional(';')),
    monadic_binding: $ => seq(optional('+'), field('name', $.identifier), ':', field('type', $._expression),
      choice('<-', '='), field('value', $._expression), optional(';')),
    do_step: $ => seq($._expression, optional(';')),
    return_expression: $ => seq('return', $._expression),
    match_function: $ => seq('\\', '{', repeat($.match_arm), optional($._expression), optional(';'), '}'),
    match_arm: $ => seq($.identifier, ':', $._expression, optional(';')),
  },
});
